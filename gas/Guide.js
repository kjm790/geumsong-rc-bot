/** 설명서를 올리고(그룹이면) 고정한다. 고정은 봇에 '메시지 고정' 권한이 있을 때만 된다 — 안 돼도 무시 */
function officePostGuide_(chatId, type, pin) {
  var res = tgSend_(chatId, officeGuideText_(type));
  if (pin && res && res.ok && res.result && res.result.message_id) {
    try { tgApi_('pinChatMessage', { chat_id: chatId, message_id: res.result.message_id, disable_notification: true }); } catch (e) {}
  }
  return res;
}

function officeCmdGuide_(c) {
  var room = c.chat.type === 'private' ? null : roomFind_(rooms_(), c.chat.id);
  officePostGuide_(c.chat.id, room ? room.type : '', false);
}
